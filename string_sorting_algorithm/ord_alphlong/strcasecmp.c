int	ft_strcasecmp(char *s1, char *s2)
{
	int	i;
	char	c1;
	char 	c2;

	i = 0;
	while (s1[i] || s2[i])
	{
		c1 = s1[i];
		c2 = s2[i];
		if (c1 >= 'A' && c1 <= 'Z')
			c1 += 32;
		if (c2 >= 'A' && c2 <= 'Z')
			c2 += 32;
		if (c1 != c2)
			return (c1 - c2);
		i++;
	}
	return (0);
}
